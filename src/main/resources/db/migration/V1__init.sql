CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE TABLE habits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(1000),
    category VARCHAR(60),
    frequency_type VARCHAR(20) NOT NULL,
    times_per_week INTEGER,
    weekdays VARCHAR(20),
    priority INTEGER NOT NULL DEFAULT 0,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT ck_habits_frequency
        CHECK (frequency_type IN ('DAILY', 'WEEKLY', 'SPECIFIC_DAYS')),
    CONSTRAINT ck_habits_times_per_week
        CHECK (times_per_week IS NULL OR times_per_week BETWEEN 1 AND 7)
);

CREATE INDEX idx_habits_user_priority
    ON habits (user_id, priority DESC, created_at ASC);

CREATE INDEX idx_habits_user_active
    ON habits (user_id)
    WHERE archived = FALSE;

CREATE TABLE habit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    habit_id BIGINT NOT NULL REFERENCES habits (id) ON DELETE CASCADE,
    log_date DATE NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_habit_logs_habit_date UNIQUE (habit_id, log_date)
);

CREATE INDEX idx_habit_logs_habit_date
    ON habit_logs (habit_id, log_date);

CREATE INDEX idx_habit_logs_date
    ON habit_logs (log_date);